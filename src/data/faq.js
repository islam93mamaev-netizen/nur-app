export function searchFaqs(query) {
  if (!query) return [];
  const q = query.toLowerCase().trim();
  return faqs.filter((f) =>
    f.question.toLowerCase().includes(q) ||
    f.short.toLowerCase().includes(q) ||
    f.answer.toLowerCase().includes(q)
  );
}
