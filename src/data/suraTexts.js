// Собирает полный блок суры из quran.js: арабский, транскрипция, перевод.
export function getSuraBlock(id) {
  const s = surahs.find((x) => x.id === id);
  if (!s) return null;
  const cyr = CYR_TRANSLIT[id];
  return {
    id,
    name: s.name,
    nameAr: s.nameAr,
    ar: s.ayats.map((a) => a.ar).join('. ') + '.',
    // Если кириллической транскрипции нет — используем латинскую из quran.js
    tr: (cyr || s.ayats.map((a) => a.tr)).join('. ') + '.',
    ru: s.ayats.map((a) => a.ru).join(' '),
  };
}

// Три защитные суры (аль-муʿаввизат + аль-Ихляс) одним блоком.
// note — необязательная приписка в конце (например, «по 3 раза»).
export function getProtectiveSurasBlock(note = '') {
  const parts = [112, 113, 114].map((id) => getSuraBlock(id));
  const suffix = note ? `\n${note}` : '';
  return {
    ar: parts.map((p) => `سُورَةُ ${p.nameAr}: ${p.ar}`).join('\n'),
    tr: parts.map((p) => `${p.name}: ${p.tr}`).join('\n') + suffix,
    ru: parts.map((p) => `${p.name}: ${p.ru}`).join('\n') + suffix,
  };
}

