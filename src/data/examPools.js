// =============================================================
// СЛОВА (words) — генератор аудио-вопросов
// =============================================================
export function buildWordsPool(count = 30) {
  // Берём count случайных слов и собираем audio-вопросы
  const shuffled = shuffle(words);
  return shuffled.slice(0, count).map((w) => {
    const same = words.filter((x) => x.category === w.category && x.id !== w.id);
    const distractors = shuffle(same).slice(0, 3).map((x) => x.ru);
    const options = shuffle([w.ru, ...distractors]);
    return {
      type: 'audio',
      q: `Что означает: ${w.ar}?`,
      options,
      answer: options.indexOf(w.ru),
      explanation: `${w.ar} (${w.tr || ''}) — «${w.ru}». Категория: ${w.category}.${w.example ? ' Пример: ' + w.example : ''}`,
    };
  });
}

