export function findModule(id) {
  return modules.find((m) => m.id === id);
}

export function findLesson(lessonId) {
  for (const m of modules) {
    const l = m.lessons.find((x) => x.id === lessonId);
    if (l) return { lesson: l, module: m };
  }
  return null;
}
