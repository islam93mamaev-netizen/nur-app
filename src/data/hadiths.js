export function getDailyHadith(date = new Date()) {
  const idx = date.getDate() % hadiths.length;
  return hadiths[idx];
}

export function getRandomHadith() {
  const idx = Math.floor(Math.random() * hadiths.length);
  return hadiths[idx];
}
